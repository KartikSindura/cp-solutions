#include <bits/stdc++.h>
using namespace std;
typedef long long ll;
#define lp(i, n) for (int i = 0; i < n; i++)
#define lps(start, n) for (int i = start; i <= n; i++)

int main() {
  int res = 0;
  int arr[5] = {-1, 1, 2, -2, 1};
  int n = 5;
  for (int i = 0; i < n; i++) {
    for (int j = 0; j < n; j++) {
      for (int k = 0; k < n; k++) {
        res += arr[i] + arr[j] + arr[k];
      }
    }
  }
  cout << res << endl;
}

